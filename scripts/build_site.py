"""Build the GitHub Pages site from *real runs* of Sentinel.

    python scripts/build_site.py            # ~2 minutes; add --perf to also regenerate docs/PERFORMANCE.md

Produces (committed, served by GitHub Pages from the repository root):
  index.html                          landing page (from site/index.template.html)
  site/demo/backtest_ema_adx.html     full backtest report (walk-forward, MC, sensitivity, holdout)
  site/demo/backtest_rsi_bb.html      second report
  site/demo/dashboard/                read-only dashboard snapshot after a paper-trading session

Every number on the landing page is produced here, by running the code: test count from
pytest, results from docs/performance.json, the gate checklist from the gate, terminal output
from the actual CLI. The dataset is the bundled synthetic one, so no network or keys are needed.
"""

from __future__ import annotations

import html
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
SITE = ROOT / "site"
DEMO = SITE / "demo"

API_ENDPOINTS = ["overview", "equity", "compare", "risk", "strategies", "journal", "health", "events", "funds"]


def log(msg: str) -> None:
    print(f"[build_site] {msg}", file=sys.stderr, flush=True)


def pct(v, d=1):
    return "–" if v is None else f"{v * 100:.{d}f}%"


def signed_cls(v):
    return "pos" if v and v > 0 else "neg" if v and v < 0 else ""


def count_tests() -> tuple[int, bool]:
    p = subprocess.run([sys.executable, "-m", "pytest", "-o", "addopts=", "-q", "-p", "no:cacheprovider"],
                       cwd=ROOT, capture_output=True, text=True)
    m = re.search(r"(\d+) passed", p.stdout)
    n = int(m.group(1)) if m else 0
    return n, p.returncode == 0 and n > 0


def build_reports(home: Path):
    from sentinel.backtest import robustness as rb
    from sentinel.backtest.report import render_report
    from sentinel.config import Settings
    from sentinel.core.state import StateStore
    from sentinel.data.synthetic import demo_universe

    data = demo_universe(timeframe="1h")
    s = Settings(app={"home": str(home)}, market={"symbols": list(data), "venue": "sim"})
    store = StateStore(home / "state.db")
    dev, hold = rb.split_holdout(data, s.backtest.holdout_fraction)
    out = {}
    for name, sens_xy in (("ema_adx", ("fast", "slow")), ("rsi_bb", ("rsi_low", "bb_k"))):
        log(f"backtest {name} (walk-forward, sensitivity, Monte Carlo, holdout)")
        res = rb.backtest_window(dev, s, name, {}, None, None)
        n = len(next(iter(dev.values())))
        wf = rb.walk_forward(dev, s, name, train_bars=n // 4, test_bars=n // 8, max_combos=12)
        tr = rb.trade_equity_returns(res)
        mc = rb.monte_carlo(tr, 2000, method="bootstrap")
        mc.max_drawdown = rb.monte_carlo(tr, 2000, method="shuffle").max_drawdown
        mc.method = "bootstrap (returns) + shuffle (drawdown)"
        sens = rb.sensitivity(dev, s, name, *sens_xy, n=4)
        ho, n_evals = rb.evaluate_holdout(hold, s, name, {}, store)
        warn = rb.overfit_warnings(res.metrics, wf, sens, mc, n_evals)
        render_report(res, f"Backtest: {name} (synthetic demo data)", DEMO / f"backtest_{name}.html", warn.to_list(),
                      wf, mc, sens, rb.by_period(res, dev[next(iter(dev))]["close"], 720),
                      rb.per_symbol(dev, s, name, {}), ho,
                      notes="SYNTHETIC DATA (regime-switching random walk): results say nothing about real markets. "
                            "Generated by scripts/build_site.py.")
        out[name] = {"metrics": res.metrics, "wf": wf, "holdout": ho.metrics}
    return out


def build_paper_and_dashboard(home: Path, expectations: dict) -> dict:
    from fastapi.testclient import TestClient

    from sentinel.cli import _paper_demo
    from sentinel.config import Settings
    from sentinel.core.state import StateStore
    from sentinel.dashboard.app import create_app, set_password
    from sentinel.funds import Funds

    s = Settings(app={"home": str(home)}, funds={"currency": "USDT", "bank_label": "Demo bank ****0000"})
    store = StateStore(home / "state.db")
    store.set("backtest.expectations", expectations)
    funds = Funds(store, "PAPER", s.funds)
    funds.deposit(2_500, "paper", "demo deposit (simulated)")  # applied by the runner on its first bar
    bars = 700
    log(f"paper trading replay ({bars} bars x 2 symbols) with a simulated deposit")
    _paper_demo(s, store, bars)
    st = store.get("paper.broker_state.PAPER")
    eq = st["cash"] + sum(p["qty"] * st["marks"].get(k, p["avg_price"]) for k, p in st["positions"].items())
    funds.request_withdrawal(500, eq, st["cash"], note="demo withdrawal request (awaiting payout)")
    pw = "site-build-" + os.urandom(6).hex()
    set_password(store, pw)
    client = TestClient(create_app(s, store))
    api = DEMO / "dashboard" / "api"
    api.mkdir(parents=True, exist_ok=True)
    for ep in API_ENDPOINTS:
        r = client.get(f"/api/{ep}", auth=("admin", pw))
        r.raise_for_status()
        body = r.json()
        if ep == "health":  # drop machine-specific details from the published snapshot
            for comp in body.get("components", {}).values():
                comp.pop("pid", None)
        (api / f"{ep}.json").write_text(json.dumps(body, default=str))
    # Static dashboard: the real UI, with fetch() redirected to the JSON snapshot.
    ui = (ROOT / "sentinel" / "dashboard" / "static" / "index.html").read_text()
    shim = """<script>
// Read-only snapshot: API calls are served from JSON captured from a real paper-trading run.
(() => {
  const realFetch = window.fetch.bind(window);
  window.fetch = async (url, opts) => {
    if (opts && (opts.method || 'GET').toUpperCase() !== 'GET') {
      alert('This is a read-only snapshot. Run Sentinel locally to use the kill switch and strategy toggles.');
      throw new Error('read-only demo');
    }
    const name = String(url).split('?')[0].replace(/^\\/api\\//, '').replace(/\\//g, '_');
    return realFetch('api/' + name + '.json');
  };
})();
</script>"""
    banner = ('<div style="background:#2b5797;color:#fff;padding:8px 16px;font-size:13px;text-align:center">'
              'Read-only snapshot of a real paper-trading session on synthetic data · '
              '<a href="../../../" style="color:#fff;text-decoration:underline">back to the Sentinel site</a></div>')
    ui = ui.replace("<title>Sentinel Dashboard</title>", "<title>Sentinel · Dashboard demo</title>"
                    '<link rel="icon" href="../../assets/favicon.svg" type="image/svg+xml">')
    ui = ui.replace("<body>", "<body>\n" + banner + "\n" + shim, 1)
    ui = ui.replace("refresh();setInterval(refresh,5000);", "refresh();")
    (DEMO / "dashboard" / "index.html").write_text(ui)
    ov = json.loads((api / "overview.json").read_text())
    return {"bars": bars, "equity": ov.get("equity"), "trades": len(store.trades("PAPER")), "store": store}


class _Cli:
    """Runs real `sentinel` commands against an isolated config and records a colourised transcript."""

    def __init__(self, home: Path, name: str, funds: dict | None = None) -> None:
        import yaml

        self.home = home
        d = yaml.safe_load((ROOT / "config" / "sentinel.example.yaml").read_text())
        d["app"]["home"] = str(home / name)
        d["logging"]["dir"] = str(home / name / "logs")
        d["ml"]["registry_dir"] = str(home / name / "models")
        if funds:
            d["funds"].update(funds)
        cfg = home / f"{name}.yaml"
        cfg.write_text(yaml.safe_dump(d))
        self.env = {"SENTINEL_CONFIG": str(cfg), "SENTINEL_DEMO_HOME": str(home / name / "demo")}
        self.lines: list[tuple[str, str]] = []

    def run(self, args: list[str], keep=None, show: bool = True) -> str:
        from typer.testing import CliRunner

        from sentinel.cli import app

        log("cli: sentinel " + " ".join(args))
        r = CliRunner().invoke(app, args, env=self.env)
        if not show:
            return r.output
        self.lines.append(("c", "$ sentinel " + " ".join(a if " " not in a else f'"{a}"' for a in args)))
        for ln in [x for x in r.output.splitlines() if x.strip() and (keep is None or keep(x))]:
            cls = "bad" if re.search(r"FAIL|refused|LOCKED|locked|HIGH", ln) else ("ok" if re.search(
                r"\[PASS\]|executed|reserved \[|completed|beats baseline: True", ln) else "")
            self.lines.append((cls, ln))
        self.lines.append(("", ""))
        return r.output

    def html(self) -> str:
        out = []
        for cls, ln in self.lines[:-1]:
            esc = html.escape(ln.replace(str(self.home), "~"))
            out.append(f'<span class="{cls}">{esc}</span>' if cls else esc)
        return "\n".join(out)


def run_cli_transcript(home: Path) -> str:
    c = _Cli(home, "cli")
    c.run(["demo", "--quick"], keep=lambda ln: not ln.startswith("Demo state") and "report:" not in ln)
    c.run(["live", "--confirm", "I understand that I can lose real money"])
    c.run(["paper", "--demo", "--max-bars", "120"])
    c.run(["kill", "--yes", "--test"])
    return c.html()


def run_money_transcript(home: Path) -> str:
    c = _Cli(home, "money", funds={"currency": "USDT"})
    c.run(["init", "--no-vault"], show=False)
    c.run(["funds", "deposit", "1000", "--note", "from my bank"])
    c.run(["paper", "--demo", "--max-bars", "300"], show=False)
    keep = ("net invested", "account value", "profit / loss", "withdrawable now", "reserved")
    c.run(["funds", "status"], keep=lambda ln: ln.strip().startswith(keep))
    c.run(["funds", "withdraw", "5000", "--profit-only"])
    out = c.run(["funds", "withdraw", "400", "--note", "to my bank"])
    m = re.search(r"withdrawal #(\d+)", out)
    if m:
        c.run(["funds", "confirm", m.group(1)])
    c.run(["funds", "status"], keep=lambda ln: ln.strip().startswith(keep))
    return c.html()


def gate_rows(store, tests_ok: bool, n_tests: int) -> str:
    from sentinel.config import Settings
    from sentinel.gate.readiness import evaluate_gate

    rep = evaluate_gate(Settings(), store, test_runner=lambda: (tests_ok, f"{n_tests} passed"))
    rows = []
    for c in rep.checks:
        st = "pass" if c.passed else "fail"
        rows.append(f'<div class="check"><span class="st {st}">{st.upper()}</span><div>{html.escape(c.name)}'
                    f"<small>{html.escape(c.detail)}</small></div></div>")
    return "".join(rows)


def perf_rows() -> str:
    perf = json.loads((ROOT / "docs" / "performance.json").read_text())
    rows = []
    for name, r in perf.items():
        wf = pct(r["wf_oos_return"]) if r["wf_oos_return"] is not None else "–"
        shp = f"{r['wf_is']:.2f} → {r['wf_oos']:.2f}" if r["wf_is"] is not None else "–"
        rows.append(
            f'<tr><td><a href="docs/strategies/{name}.html">{name}</a></td>'
            f'<td class="{signed_cls(r["is_return"])}">{pct(r["is_return"])}</td><td>{pct(r["bench"])}</td>'
            f'<td class="{signed_cls(r["wf_oos_return"])}">{wf}</td><td>{shp}</td>'
            f'<td class="{signed_cls(r["ho_return"])}">{pct(r["ho_return"])}</td><td>{pct(r["mdd"])}</td>'
            f'<td>{r["trades"]}</td></tr>')
    return "".join(rows)


def main() -> None:
    t0 = time.time()
    if "--perf" in sys.argv:
        subprocess.run([sys.executable, str(ROOT / "scripts" / "generate_performance.py")], check=True)
    if DEMO.exists():
        shutil.rmtree(DEMO)
    DEMO.mkdir(parents=True)
    log("running test suite")
    n_tests, tests_ok = count_tests()
    log(f"{n_tests} tests, ok={tests_ok}")
    if not tests_ok:
        raise SystemExit("tests failing: refusing to publish a site that claims they pass")
    with tempfile.TemporaryDirectory() as td:
        home = Path(td)
        reports = build_reports(home)
        m = reports["ema_adx"]["metrics"]
        span_w = 14016 / (24 * 7)
        exp = {"strategy": "ema_adx", "params": {}, "expectancy_pct": m["expectancy_pct"], "win_rate": m["win_rate"],
               "max_drawdown": m["max_drawdown"], "sharpe": m["sharpe"], "trades_per_week": m["trades"] / span_w,
               "oos_expectancy_pct": reports["ema_adx"]["wf"].oos_metrics.get("expectancy_pct"), "demo": True}
        paper = build_paper_and_dashboard(home / "paper", exp)
        gates = gate_rows(paper["store"], tests_ok, n_tests)
        terminal = run_cli_transcript(home)
        money_terminal = run_money_transcript(home)
    sha = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True,
                         text=True).stdout.strip() or "local"
    build = time.strftime("%Y-%m-%d", time.gmtime())
    page = (SITE / "index.template.html").read_text()
    subs = {
        "TESTS": str(n_tests), "BUILD": build, "SHA": sha, "PERF_ROWS": perf_rows(), "GATE_ROWS": gates,
        "TERMINAL": terminal, "MONEY_TERMINAL": money_terminal, "PAPER_BARS": str(paper["bars"]),
        "PAPER_EQUITY": f"{paper['equity']:,.2f} from a 10,000 start" if paper["equity"] else "–",
        "PAPER_TRADES": str(paper["trades"]),
    }
    for k, v in subs.items():
        page = page.replace(f"<!--@{k}@-->", v)
    left = re.findall(r"<!--@(\w+)@-->", page)
    if left:
        raise SystemExit(f"unfilled placeholders: {left}")
    (ROOT / "index.html").write_text(page)
    log(f"done in {time.time() - t0:.0f}s → index.html, site/demo/")


if __name__ == "__main__":
    main()
